"""The real engine of the offline runs (EVAL-06): one fresh Engine per case, frozen inputs.

EvalRuntime starts the MCP servers once per run, on the demo database generated by the
harness, then builds a fresh Engine for each case (EvalRuntime.new_engine): its own
Ollama client, history, memory store and judge. The harness uses it through
EvalRuntime.factory; the adversarial suite (SEC-02) and the long conversations (EVAL-10)
call new_engine directly.

What makes two runs give the same figures (judge.md §3):
- the data: one seed and one reference date for the demo database;
- the date: the time server is replaced by FrozenClock, which always answers the
  reference date under the same tool name (the system prompt does not change);
- the model: temperature 0 and Ollama's options.seed on every call, judge included
  (SeededOllamaClient);
- the memory: a fresh memory.db per case, filled by the harness.

The engine confirms nothing (AutoRejectBroker by default): a write asked by the model is
refused, so the demo database is never changed.
"""

