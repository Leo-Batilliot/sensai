# Same name as the date tool of mcp-server-time in config.example.toml (MCP-06)
FROZEN_CLOCK = f"time__{DATE_TOOL_SUFFIX}"
CLOCK_TIMEZONE = "Europe/Paris"
CLOCK_TIME = time(9, 0)  # a run happens on the morning of the reference date
TIME_SERVER_PACKAGE = "mcp-server-time"
PROMPT_NAME = "system_sql"
# system_sql_v1.md -> v1: the file name carries the version (registry.toml, A4)
_PROMPT_VERSION = re.compile(r"_(v\d+)\.md$")


class FrozenClock:
    """Native stand-in for time__get_current_time, always on the reference date.

    Answers like mcp-server-time (timezone, datetime, day_of_week, is_dst), so that
    the model reads the same thing as in the demo.
    """

    name = FROZEN_CLOCK
    description = "Donne la date et l'heure actuelles dans un fuseau horaire."
    input_schema: dict[str, Any] = {
        "type": "object",
        "properties": {
            "timezone": {
                "type": "string",
                "description": f"Fuseau IANA, par exemple « {CLOCK_TIMEZONE} »",
            }
        },
        "required": ["timezone"],
        "additionalProperties": False,
    }
    annotations = ToolAnnotations(
        read_only=True, destructive=False, idempotent=True, open_world=False
    )

    def __init__(self, today: date) -> None:
        self.today = today

    async def call(self, arguments: dict[str, Any]) -> ToolResult:
        now = frozen_now(self.today)
        data = {
            "timezone": CLOCK_TIMEZONE,
            "datetime": now.isoformat(timespec="seconds"),
            "day_of_week": now.strftime("%A"),
            "is_dst": bool(now.dst()),
        }
        text = json.dumps(data, ensure_ascii=False)
        return ToolResult(ok=True, text=text, summary=data["datetime"], data=data)


def frozen_now(today: date) -> datetime:
    """The reference date at CLOCK_TIME in Europe/Paris (UTC if tzdata is missing)."""
    try:
        from zoneinfo import ZoneInfo, ZoneInfoNotFoundError
    except ImportError:  # pragma: no cover - zoneinfo is in the stdlib since 3.9
        return datetime.combine(today, CLOCK_TIME, timezone.utc)
    try:
        zone = ZoneInfo(CLOCK_TIMEZONE)
    except ZoneInfoNotFoundError:  # Windows without the tzdata package
        return datetime.combine(today, CLOCK_TIME, timezone.utc)
    return datetime.combine(today, CLOCK_TIME, zone)


class SeededOllamaClient(OllamaClient):
    """An OllamaClient that sends options.seed with every chat request."""

    def __init__(self, host: str, *, seed: int, **kwargs: Any) -> None:
        super().__init__(host, **kwargs)
        self.seed = seed

    def chat_stream(
        self,
        model: str,
        messages: list[Message],
        *,
        options: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> AsyncGenerator[Chunk, None]:
        return super().chat_stream(model, messages, options=self._seeded(options), **kwargs)

    async def chat(
        self,
        model: str,
        messages: list[Message],
        *,
        options: dict[str, Any] | None = None,
        **kwargs: Any,
    ) -> Chunk:
        return await super().chat(model, messages, options=self._seeded(options), **kwargs)

    def _seeded(self, options: dict[str, Any] | None) -> dict[str, Any]:
        return {**(options or {}), "seed": self.seed}


ClientFactory = Callable[[Config], ChatClient]


def eval_config(config: Config, business_db: Path, memory_db: Path | None = None) -> Config:
    """The configuration of a run: temperature 0, the run's databases, no time server.

    The time server gives the real time and cannot be frozen: FrozenClock replaces it.
    sql_toolbox always reads the run's database, even if config.toml gives it a --db.
    """
    servers = {
        name: _on_run_database(server)
        for name, server in config.mcp.servers.items()
        if not is_time_server(name, server)
    }
    database = {"business_path": business_db}
    if memory_db is not None:
        database["memory_path"] = memory_db
    return config.model_copy(
        update={
            "agent": config.agent.model_copy(update={"temperature": 0.0}),
            "database": config.database.model_copy(update=database),
            "mcp": config.mcp.model_copy(update={"servers": servers}),
        }
    )


def is_time_server(name: str, server: McpServerConfig) -> bool:
    return name == "time" or any(TIME_SERVER_PACKAGE in arg for arg in server.args)


def _on_run_database(server: McpServerConfig) -> McpServerConfig:
    args = list(server.args)
    if SQL_TOOLBOX_MODULE not in args or "--db" not in args:
        return server
    index = args.index("--db")
    del args[index : index + 2]  # the McpManager adds [database] business_path back
    return server.model_copy(update={"args": tuple(args)})


def prompt_info(file: str = SYSTEM_SQL) -> dict[str, str | None]:
    """Name, version and fingerprint of the system prompt (A4), for the report."""
    data = resources.files("sensai.core").joinpath("prompts", file).read_bytes()
    match = _PROMPT_VERSION.search(file)
    return {
        "name": PROMPT_NAME,
        "version": match.group(1) if match else None,
        "file": file,
        "sha256": hashlib.sha256(data).hexdigest(),
    }


class EvalEngine:
    """An Engine of a run, with its own memory store, closed together."""

    def __init__(self, engine: Engine, store: MemoryStore) -> None:
        self.engine = engine
        self.store = store

    def run_turn(self, user_message: str) -> AsyncIterator[events.Event]:
        return self.engine.run_turn(user_message)

    def json_stats(self) -> dict[str, dict[str, int]]:
        """T5 counters since the engine was built: tool arguments and judge reports."""
        judge = self.engine.judge
        return {
            "tool_arguments": self.engine.argument_stats.to_dict(),
            "judge": judge.judge.stats.to_dict() if judge is not None else _no_calls(),
        }

    async def aclose(self) -> None:
        try:
            await self.engine.aclose()
        finally:
            self.store.close()


class EvalRuntime:
    """MCP servers started once per run, a fresh Engine per case.

    Use it as an async context manager, or call aclose() at the end of the run.
    """

    def __init__(
        self,
        config: Config,
        *,
        seed: int = 42,
        client_factory: ClientFactory | None = None,
        manager_factory: Callable[[Config], McpManager] = McpManager.from_config,
    ) -> None:
        self.base_config = config
        self.seed = seed
        self.client_factory = client_factory or self._seeded_client
        self.manager_factory = manager_factory
        self.config: Config | None = None
        self.manager: McpManager | None = None
        self._prompt: PromptTemplate | None = None

    async def __aenter__(self) -> EvalRuntime:
        return self

    async def __aexit__(self, *exc_info: object) -> None:
        await self.aclose()

    async def start(self, business_db: Path) -> None:
        """Start the MCP servers on the run's database and build the system prompt."""
        if self.config is not None:
            if self.config.database.business_path != business_db:
                raise RuntimeError("EvalRuntime already started on another database")
            return
        self.config = eval_config(self.base_config, business_db)
        self.manager = self.manager_factory(self.config)
        await self.manager.start_all()
        with MemoryStore.open(":memory:") as store:
            names = [info.name for info in self._registry(store, None, date.min).tools()]
        self._prompt = system_prompt_template(business_db, names)

    async def aclose(self) -> None:
        if self.manager is not None:
            await self.manager.stop_all()
            self.manager = None

    def new_engine(
        self, memory_db: Path, today: date, broker: ConfirmationBroker | None = None
    ) -> EvalEngine:
        """A fully wired Engine on a memory.db of its own (tools, HITL, memory, judge)."""
        if self.config is None or self._prompt is None:
            raise RuntimeError("EvalRuntime.start() must run before the first engine")
        config = self.config.model_copy(
            update={"database": self.config.database.model_copy(update={"memory_path": memory_db})}
        )
        store = MemoryStore.open(memory_db)
        session_id = new_id()
        client = self.client_factory(config)
        engine = Engine(
            config,
            client,
            registry=self._registry(store, session_id, today),
            system_prompt=self._prompt,
            broker=broker,
            session_id=session_id,
            memory=MemoryContext(store),
            judge=OnlineJudge.from_config(config, client),
        )
        return EvalEngine(engine, store)

    async def factory(self, entry: GoldenEntry, setup: RunSetup) -> TurnEngine:
        """The EngineFactory of the harness (run_suite, run_and_report)."""
        await self.start(setup.business_db)
        return self.new_engine(setup.memory_db, setup.today)

    def info(self) -> dict[str, Any]:
        """What the report records about the run (judge.md §5)."""
        config = self.base_config
        return {
            "model": config.ollama.model,
            "judge_model": config.ollama.effective_judge_model,
            "judge_enabled": config.eval.judge_enabled,
            "temperature": 0.0,
            "ollama_seed": self.seed,
            "num_ctx": config.ollama.num_ctx,
            "persona": None,  # profiles arrive with A5 (PERS-01)
            "prompt": prompt_info(),
            "fewshot": {"enabled": False, "bank": None},  # dynamic examples: A7 (FEWSHOT-01)
            "date_tool": "frozen",
        }

    def _registry(self, store: MemoryStore, session_id: str | None, today: date) -> Registry:
        tools: list[Tool] = [*memory_tools(store, session_id), FrozenClock(today)]
        return Registry(
            self.manager,
            tools,
            previewers={MEMORY_DELETE: lambda args: store.delete_impact(args["kind"], args["ref"])},
        )

    def _seeded_client(self, config: Config) -> ChatClient:
        return SeededOllamaClient(
            config.ollama.host,
            seed=self.seed,
            timeout_s=config.ollama.timeout_s,
            keep_alive=config.ollama.keep_alive,
        )


async def check_models(config: Config) -> str | None:
    """Why a run cannot start (Ollama down, model missing), in French; None if it can.

    Checked before the run: otherwise every question would end in the same error.
    """
    async with OllamaClient(config.ollama.host, timeout_s=config.ollama.timeout_s) as client:
        try:
            installed = set(await client.list_models())
        except SensaiError as exc:
            return exc.message
    for model in dict.fromkeys((config.ollama.model, config.ollama.effective_judge_model)):
        if model not in installed and f"{model}:latest" not in installed:
            return ModelNotFound(model).message
    return None


def _no_calls() -> dict[str, int]:
    return {"first_try": 0, "repaired": 0, "failed": 0}


