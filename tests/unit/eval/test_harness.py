async def test_run_and_report_writes_both_reports(tmp_path: Path) -> None:
    suite = tmp_path / "suite.jsonl"
    suite.write_text(
        "\n".join(json.dumps(dataclasses.asdict(GOLDEN[i])) for i in ("q005", "q014")) + "\n",
        encoding="utf-8",
    )

    path = await run_and_report(
        suite,
        scripted_factory,
        tag="v0.5",
        today=REFERENCE_DATE,
        info={"model": "qwen3:8b", "judge_model": "qwen3:8b"},
        memory_rules_path=ROOT / "eval/memory_rules.json",
        reports_dir=tmp_path / "reports",
        run_day=date(2026, 10, 13),
    )

    assert path == tmp_path / "reports/2026-10-13_v0.5.json"
    report = load_report(path)
    assert (report["tag"], report["questions"], report["today"], report["seed"]) == (
        "v0.5",
        2,
        "2026-10-20",
        42,
    )
    assert report["metrics"]["ex"] == {"value": 1.0, "n": 1}
    assert [result["id"] for result in report["results"]] == ["q005", "q014"]
    markdown = path.with_suffix(".md").read_text(encoding="utf-8")
    assert "# Rapport d'évaluation — v0.5" in markdown
    assert "| EX (exactitude d'exécution) | 1.00 | 1 |" in markdown
