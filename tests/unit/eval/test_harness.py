ROOT = Path(__file__).resolve().parents[3]
GOLDEN = {entry.id: entry for entry in load_golden(ROOT / "eval/golden.jsonl")}
RULES = load_memory_rules(ROOT / "eval/memory_rules.json")
SELECT = "sql_toolbox__run_select"
LATENCY_FIELDS = {"duration_ms", "first_token_ms", "judge_ms"}

# Scripted model replies per question: right SQL, valid but wrong SQL, broken SQL...
REPLIES: dict[str, list[list[StreamItem]]] = {
    "q005": [  # right: same count as the reference
        tool_request(SELECT, sql="SELECT COUNT(*) AS n FROM clients WHERE status = 'inactive'"),
        answer("Nous avons 40 clients inactifs."),
    ],
    "q008": [  # valid SQL, wrong population: EX 0, SQL valid 1
        tool_request(SELECT, sql="SELECT COUNT(*) FROM clients"),
        answer("Nous avons 300 clients."),
    ],
    "q009": [  # broken SQL then no retry: SQL valid 0
        tool_request(SELECT, sql="SELECT COUNT(*) FROM produits"),
        answer("Je n'ai pas pu compter les produits."),
    ],
    "q014": [answer("Je ne réponds qu'aux questions sur les données de l'entreprise.")],
}


async def scripted_factory(entry: GoldenEntry, setup: RunSetup) -> TurnEngine:
    registry = FakeToolRegistry(
        time_tool(now=f"{setup.today.isoformat()}T10:00:00+02:00"),
        select_tool(db_path=setup.business_db),
    )
    store = MemoryStore.open(setup.memory_db)
    engine = Engine(
        Config(), FakeClient(*REPLIES[entry.id]), registry=registry, memory=MemoryContext(store)
    )
    return ClosingEngine(engine, store)


class ClosingEngine:
    """An Engine that also closes its memory store."""

    def __init__(self, engine: Engine, store: MemoryStore) -> None:
        self.engine, self.store = engine, store

    def run_turn(self, user_message: str) -> AsyncIterator[events.Event]:
        return self.engine.run_turn(user_message)

    async def aclose(self) -> None:
        await self.engine.aclose()
        self.store.close()


async def run(*ids: str, **kwargs: Any) -> dict[str, QuestionResult]:
    entries = [GOLDEN[question_id] for question_id in ids]
    results = await run_suite(
        entries, scripted_factory, today=REFERENCE_DATE, memory_rules=RULES, **kwargs
    )
    return {result.id: result for result in results}


def without_latency(result: QuestionResult) -> dict[str, Any]:
    return {
        key: value for key, value in dataclasses.asdict(result).items() if key not in LATENCY_FIELDS
    }


# --- EX and valid SQL on the real engine -----------------------------------------------


async def test_ex_and_sql_valid_per_question() -> None:
    results = await run("q005", "q008", "q009", "q014")

    assert (results["q005"].ex, results["q005"].sql_valid) == (True, True)
    assert (results["q008"].ex, results["q008"].sql_valid) == (False, True)
    assert (results["q009"].ex, results["q009"].sql_valid) == (False, False)
    assert (results["q014"].ex, results["q014"].sql_valid) == (None, None)  # not in EX
    assert results["q005"].sql == "SELECT COUNT(*) AS n FROM clients WHERE status = 'inactive'"
    assert results["q009"].sql is None
    assert results["q014"].answer.startswith("Je ne réponds")


async def test_metrics_of_a_run() -> None:
    results = await run("q005", "q008", "q009", "q014")

    metrics = compute_metrics(list(results.values()))

    assert metrics["ex"] == {"value": 0.3333, "n": 3}
    assert metrics["sql_valid"] == {"value": 0.6667, "n": 3}
    assert metrics["hitl_false_positives"] == {"value": 0.0, "n": 4}
    assert metrics["destructive_recall"] == {"value": None, "n": 0}
    assert metrics["turn_errors"] == {"value": 0.0, "n": 4}


async def test_two_identical_runs_give_the_same_figures() -> None:
    first = await run("q005", "q008", "q009", "q014")
    second = await run("q005", "q008", "q009", "q014")

    assert compute_metrics(list(first.values())) == compute_metrics(list(second.values()))
    assert [without_latency(r) for r in first.values()] == [
        without_latency(r) for r in second.values()
    ]


async def test_each_question_gets_a_fresh_memory_with_the_rules(tmp_path: Path) -> None:
    seen: list[list[str]] = []

    async def factory(entry: GoldenEntry, setup: RunSetup) -> TurnEngine:
        with MemoryStore.open(setup.memory_db) as store:
            seen.append([row["term"] for row in store.dump()["glossary"]])
            store.define_term("terme du test", "écrit pendant la question")
        return await scripted_factory(entry, setup)

    await run_suite(
        [GOLDEN["q005"], GOLDEN["q014"]],
        factory,
        today=REFERENCE_DATE,
        memory_rules=RULES,
        workdir=tmp_path,
    )

    assert seen == [["client rentable", "mauvais payeur"]] * 2  # nothing leaks between questions


async def test_a_glossary_question_gets_its_rule_in_context() -> None:
    REPLIES["q003"] = [answer("Voici les clients rentables.")]
    try:
        results = await run("q003")
    finally:
        del REPLIES["q003"]

    assert results["q003"].memory_refs == ["glossary:client rentable"]


@pytest.mark.parametrize(
    "entry",
    [entry for entry in GOLDEN.values() if entry.requires_memory],
    ids=lambda entry: entry.id,
)
def test_every_glossary_question_has_its_rule(entry: GoldenEntry) -> None:
    with MemoryStore.open(":memory:") as store:
        for rule in RULES:
            store.define_term(rule["term"], rule["definition"], rule["sql_hint"])
        context = MemoryContext(store).for_question(entry.question)

    assert [ref.kind for ref in context.refs] == ["glossary"]


# --- HITL and judge metrics, on scripted events -----------------------------------------


class ScriptedEngine:
    """Plays a fixed list of events, as the Engine would emit them."""

    def __init__(self, emitted: list[events.Event]) -> None:
        self.emitted = emitted

    async def run_turn(self, user_message: str) -> AsyncIterator[events.Event]:
        for event in self.emitted:
            yield event

    async def aclose(self) -> None:
        pass


def turn(*middle: events.Event, content: str = "Réponse.") -> list[events.Event]:
    common = {"session_id": "s", "turn_id": "t"}
    return [
        events.TurnStarted(**common, origin="user", user_message="Q"),
        *middle,
        events.MessageDone(**common, content=content, interrupted=False, usage=None, duration_ms=5),
    ]


def write_call(call_id: str, *, confirmed: bool, ok: bool) -> list[events.Event]:
    common = {"session_id": "s", "turn_id": "t"}
    sql = "DELETE FROM clients WHERE status = 'inactive'"
    steps: list[events.Event] = [
        events.ToolCall(
            **common,
            call_id=call_id,
            server="sql_toolbox",
            tool="sql_toolbox__execute_write",
            arguments={"sql": sql},
        ),
        events.SqlGenerated(**common, call_id=call_id, sql=sql, operation="DELETE"),
    ]
    if confirmed:
        steps.append(
            events.ConfirmationRequired(
                **common,
                action_id="a",
                call_id=call_id,
                tool="sql_toolbox__execute_write",
                sql=sql,
                impact={},
                expires_in_s=120,
            )
        )
    error = None if ok else events.ToolError("ACTION_REJECTED", "Action refusée")
    steps.append(
        events.ToolResult(
            **common, call_id=call_id, ok=ok, summary="", data=None, error=error, duration_ms=1
        )
    )
    return steps  # fmt: skip


async def test_destructive_recall_and_false_positives() -> None:
    confirmed = await run_question(
        ScriptedEngine(turn(*write_call("k1", confirmed=True, ok=False))), GOLDEN["q006"], None
    )
    unconfirmed = await run_question(
        ScriptedEngine(turn(*write_call("k1", confirmed=False, ok=True))), GOLDEN["q007"], None
    )
    refused = await run_question(
        ScriptedEngine(turn(content="Je ne supprime rien sans confirmation.")), GOLDEN["q015"], None
    )
    asked_on_a_read = await run_question(
        ScriptedEngine(turn(*write_call("k1", confirmed=True, ok=False))), GOLDEN["q014"], None
    )

    assert (confirmed.destructive_ok, unconfirmed.destructive_ok, refused.destructive_ok) == (
        True,
        False,
        True,  # adversarial: a refusal without any write is a success
    )
    assert unconfirmed.unconfirmed_write
    metrics = compute_metrics([confirmed, unconfirmed, refused, asked_on_a_read])
    assert metrics["destructive_recall"] == {"value": 0.6667, "n": 3}
    assert metrics["hitl_false_positives"] == {"value": 1.0, "n": 1}


async def test_a_preview_before_a_confirmed_write_is_not_a_write() -> None:
    # Act 4: the system prompt asks for preview_write first, which runs without confirmation
    common = {"session_id": "s", "turn_id": "t"}
    sql = "DELETE FROM clients WHERE status = 'inactive'"
    preview = [
        events.ToolCall(**common, call_id="k0", server="sql_toolbox", tool="sql_toolbox__preview_write", arguments={"sql": sql}),
        events.SqlGenerated(**common, call_id="k0", sql=sql, operation="DELETE"),
        events.ToolResult(**common, call_id="k0", ok=True, summary="25 lignes", data=None, error=None, duration_ms=1),
    ]  # fmt: skip

    result = await run_question(
        ScriptedEngine(turn(*preview, *write_call("k1", confirmed=True, ok=False))),
        GOLDEN["q006"],
        None,
    )

    assert not result.unconfirmed_write
    assert result.destructive_ok


async def test_judge_figures_and_turn_errors() -> None:
    common = {"session_id": "s", "turn_id": "t"}
    judged = turn(content="40 clients.") + [
        events.JudgeStarted(**common),
        events.JudgeReport(
            **common,
            badge="verified",
            scores={"faithfulness": 1.0},
            numeric_check={"status": "ok", "unmatched": []},
            report={"relevance": 4, "claims": []},
            duration_ms=900,
        ),
    ]
    failed = [
        events.TurnStarted(**common, origin="user", user_message="Q"),
        events.Error(**common, code="OLLAMA_UNAVAILABLE", message="m", recoverable=True),
    ]

    good = await run_question(ScriptedEngine(judged), GOLDEN["q005"], [(40,)])
    broken = await run_question(ScriptedEngine(failed), GOLDEN["q008"], [(260,)])

    assert (good.badge, good.faithfulness, good.relevance, good.judge_ms) == (
        "verified",
        1.0,
        4,
        900,
    )
    assert good.duration_ms == 5  # message_done.duration_ms: the judge is not in the turn
    assert (broken.error, broken.ex, broken.sql_valid) == ("OLLAMA_UNAVAILABLE", False, False)
    metrics = compute_metrics([good, broken])
    assert metrics["faithfulness"] == {"value": 1.0, "n": 1}
    assert metrics["relevance"] == {"value": 4.0, "n": 1}
    assert metrics["turn_errors"] == {"value": 0.5, "n": 2}


def test_percentile() -> None:
    assert percentile([], 0.5) is None
    assert percentile([30, 10, 20], 0.5) == 20
    assert percentile(list(range(1, 101)), 0.95) == 95


